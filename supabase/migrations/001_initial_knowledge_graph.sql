-- Initial, additive schema for the documentary research corpus.
-- PostgreSQL 16+ / Supabase-compatible; no extensions or destructive DDL.
BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
  version text PRIMARY KEY,
  name text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS knowledge_base_metadata (
  singleton_id smallint PRIMARY KEY DEFAULT 1 CHECK (singleton_id = 1),
  dataset_version text NOT NULL,
  researched_on date,
  language text,
  title text NOT NULL,
  scope text,
  conventions jsonb NOT NULL DEFAULT '{}'::jsonb,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  imported_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dataset_imports (
  source_sha256 text PRIMARY KEY,
  source_name text NOT NULL,
  dataset_version text NOT NULL,
  imported_at timestamptz NOT NULL DEFAULT now(),
  record_counts jsonb NOT NULL,
  import_note text NOT NULL DEFAULT 'Append-only initial JSON import'
);

CREATE TABLE IF NOT EXISTS entities (
  entity_id text PRIMARY KEY,
  canonical_name text NOT NULL CHECK (btrim(canonical_name) <> ''),
  normalized_name text NOT NULL CHECK (btrim(normalized_name) <> ''),
  entity_type text NOT NULL,
  research_cluster text,
  note text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sources (
  source_id text PRIMARY KEY,
  title text NOT NULL CHECK (btrim(title) <> ''),
  source_url text NOT NULL,
  author text,
  publisher text,
  source_type text,
  published_on date,
  published_year integer,
  published_at_raw text,
  accessed_on date,
  passage_locator text,
  access_note text,
  local_file_path text,
  sha256 text,
  original_sha256 text,
  independence_key text,
  independence_assessment text NOT NULL DEFAULT 'unreviewed',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (published_year IS NULL OR published_year BETWEEN 1 AND 9999)
);

CREATE TABLE IF NOT EXISTS entity_aliases (
  alias_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id text NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
  alias text NOT NULL CHECK (btrim(alias) <> ''),
  normalized_alias text NOT NULL CHECK (btrim(normalized_alias) <> ''),
  alias_type text NOT NULL DEFAULT 'alternate_name',
  source_id text REFERENCES sources(source_id) ON DELETE RESTRICT,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  UNIQUE (entity_id, normalized_alias)
);

CREATE TABLE IF NOT EXISTS investigation_cases (
  case_id text PRIMARY KEY,
  title text NOT NULL,
  period_label text,
  sphere text,
  actors jsonb NOT NULL DEFAULT '[]'::jsonb,
  mechanism text,
  intended_decision text,
  outcome text,
  beneficiaries jsonb NOT NULL DEFAULT '[]'::jsonb,
  competing_explanations jsonb NOT NULL DEFAULT '[]'::jsonb,
  conclusion text,
  limitations jsonb NOT NULL DEFAULT '[]'::jsonb,
  missing_documents jsonb NOT NULL DEFAULT '[]'::jsonb,
  map_entity_id text REFERENCES entities(entity_id) ON DELETE RESTRICT,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS relationships (
  relationship_id text PRIMARY KEY,
  source_entity_id text NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
  target_entity_id text NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
  relation_type text NOT NULL,
  weight smallint NOT NULL CHECK (weight BETWEEN 1 AND 5),
  period_label text,
  period_start_year integer,
  period_end_year integer,
  start_on date,
  start_year integer,
  start_raw text,
  end_on date,
  end_year integer,
  end_raw text,
  assertion text NOT NULL,
  limitation text,
  review_status text NOT NULL,
  epistemic_status text NOT NULL CHECK (epistemic_status IN
    ('source_linked_claim','identification','hypothesis','announced','inference','contradicted','needs_review')),
  confidence text,
  reference_on date,
  reference_year integer,
  reference_raw text,
  case_id text REFERENCES investigation_cases(case_id) ON DELETE RESTRICT,
  research_scope text,
  amount numeric,
  currency text,
  gross_positive_amount numeric,
  negative_adjustments numeric,
  amount_nature text,
  capital_pct numeric,
  fec_recipient_id text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (start_year IS NULL OR start_year BETWEEN 1 AND 9999),
  CHECK (end_year IS NULL OR end_year BETWEEN 1 AND 9999),
  CHECK (reference_year IS NULL OR reference_year BETWEEN 1 AND 9999),
  CHECK (period_start_year IS NULL OR period_start_year BETWEEN 1 AND 9999),
  CHECK (period_end_year IS NULL OR period_end_year BETWEEN 1 AND 9999),
  CHECK (capital_pct IS NULL OR capital_pct BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS evidence (
  evidence_id text PRIMARY KEY,
  relationship_id text NOT NULL REFERENCES relationships(relationship_id) ON DELETE RESTRICT,
  source_id text NOT NULL REFERENCES sources(source_id) ON DELETE RESTRICT,
  evidence_level text NOT NULL CHECK (evidence_level IN
    ('citation_reference','passage_checked','excerpt_checked','contradictory_source')),
  passage_locator text,
  summary text,
  summary_basis text NOT NULL DEFAULT 'relationship_assertion',
  excerpt_text text,
  independence_key text,
  verification_note text,
  verified_at timestamptz,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (relationship_id, source_id)
);

CREATE TABLE IF NOT EXISTS investigation_case_sources (
  case_id text NOT NULL REFERENCES investigation_cases(case_id) ON DELETE RESTRICT,
  source_id text NOT NULL REFERENCES sources(source_id) ON DELETE RESTRICT,
  ordinal integer NOT NULL DEFAULT 1 CHECK (ordinal > 0),
  PRIMARY KEY (case_id, source_id)
);

CREATE TABLE IF NOT EXISTS investigation_case_relationships (
  case_id text NOT NULL REFERENCES investigation_cases(case_id) ON DELETE RESTRICT,
  relationship_id text NOT NULL REFERENCES relationships(relationship_id) ON DELETE RESTRICT,
  ordinal integer NOT NULL DEFAULT 1 CHECK (ordinal > 0),
  PRIMARY KEY (case_id, relationship_id)
);

CREATE TABLE IF NOT EXISTS investigation_case_entities (
  case_id text NOT NULL REFERENCES investigation_cases(case_id) ON DELETE RESTRICT,
  entity_id text NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
  ordinal integer NOT NULL DEFAULT 1 CHECK (ordinal > 0),
  role_label text NOT NULL DEFAULT 'listed_in_case_map',
  PRIMARY KEY (case_id, entity_id)
);

CREATE TABLE IF NOT EXISTS events (
  event_id text PRIMARY KEY REFERENCES entities(entity_id) ON DELETE RESTRICT,
  event_type text,
  description text,
  occurred_on date,
  occurred_year integer,
  occurred_at_raw text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  CHECK (occurred_year IS NULL OR occurred_year BETWEEN 1 AND 9999)
);

CREATE TABLE IF NOT EXISTS entity_summaries (
  summary_id text PRIMARY KEY,
  entity_id text NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
  summary_version integer NOT NULL CHECK (summary_version > 0),
  summary_type text NOT NULL,
  summary_text text NOT NULL,
  summary_status text NOT NULL DEFAULT 'imported_unreviewed'
    CHECK (summary_status IN ('imported_unreviewed','draft','reviewed','superseded')),
  source_sha256 text REFERENCES dataset_imports(source_sha256) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (entity_id, summary_type, summary_version)
);

CREATE TABLE IF NOT EXISTS investigation_paths (
  path_id text PRIMARY KEY,
  title text NOT NULL,
  path_type text,
  path_status text NOT NULL DEFAULT 'curated_internal',
  source_dataset text NOT NULL,
  source_version text,
  definition jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
