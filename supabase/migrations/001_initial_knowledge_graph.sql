CREATE OR REPLACE VIEW relationship_evidence AS
SELECT r.relationship_id, r.source_entity_id, r.target_entity_id,
       r.relation_type, r.assertion, r.limitation, r.review_status,
       r.epistemic_status, ev.evidence_id, ev.evidence_level,
       ev.passage_locator, ev.summary, ev.summary_basis,
       s.source_id, s.title AS source_title, s.source_url,
       s.author AS source_author, s.publisher AS source_publisher,
       s.published_at_raw, s.accessed_on, s.access_note,
       ev.independence_key
FROM relationships r
JOIN evidence ev ON ev.relationship_id = r.relationship_id
JOIN sources s ON s.source_id = ev.source_id;

-- The caller supplies NFD/diacritic-folded lowercase text from its application.
CREATE OR REPLACE FUNCTION search_entities(
  normalized_query text,
  entity_type_filter text DEFAULT NULL,
  period_from integer DEFAULT NULL,
  period_to integer DEFAULT NULL,
  result_limit integer DEFAULT 20
)
RETURNS TABLE (
  entity_id text,
  canonical_name text,
  entity_type text,
  research_cluster text,
  matched_as text
)
LANGUAGE sql STABLE AS $$
  WITH q AS (SELECT lower(btrim(coalesce(normalized_query, ''))) AS term),
  candidates AS (
    SELECT e.entity_id, e.canonical_name, e.entity_type, e.research_cluster,
           CASE WHEN e.normalized_name = (SELECT term FROM q)
                THEN 'canonical_name' ELSE 'alias' END AS matched_as,
           CASE WHEN e.normalized_name = (SELECT term FROM q) THEN 0
                WHEN e.normalized_name LIKE (SELECT term || '%' FROM q) THEN 1
                ELSE 2 END AS match_rank
    FROM entities e
    WHERE (SELECT term <> '' FROM q)
      AND (entity_type_filter IS NULL OR e.entity_type = entity_type_filter)
      AND (
        e.normalized_name LIKE ('%' || (SELECT term FROM q) || '%')
        OR EXISTS (
          SELECT 1 FROM entity_aliases a
          WHERE a.entity_id = e.entity_id
            AND a.normalized_alias LIKE ('%' || (SELECT term FROM q) || '%')
        )
      )
      AND (
        period_from IS NULL AND period_to IS NULL
        OR EXISTS (
          SELECT 1 FROM relationships r
          WHERE (r.source_entity_id = e.entity_id OR r.target_entity_id = e.entity_id)
            AND (r.period_start_year IS NOT NULL OR r.period_end_year IS NOT NULL
                 OR r.start_year IS NOT NULL OR r.end_year IS NOT NULL OR r.reference_year IS NOT NULL)
            AND coalesce(r.period_end_year, r.end_year, r.reference_year, 9999) >= coalesce(period_from, 1)
            AND coalesce(r.period_start_year, r.start_year, r.reference_year, 1) <= coalesce(period_to, 9999)
        )
      )
  )
  SELECT c.entity_id, c.canonical_name, c.entity_type, c.research_cluster, c.matched_as
  FROM candidates c
  ORDER BY c.match_rank, c.canonical_name
  LIMIT least(greatest(coalesce(result_limit, 20), 1), 100)
$$;

-- Bounded, undirected neighborhood suitable for a map response; max depth 3 and 500 nodes.
CREATE OR REPLACE FUNCTION graph_neighborhood(
  root_entity_id text,
  max_depth integer DEFAULT 2,
  node_limit integer DEFAULT 250,
  evidence_limit integer DEFAULT 300
)
RETURNS jsonb
LANGUAGE sql STABLE AS $$
  WITH RECURSIVE walk(entity_id, depth, visited) AS (
    SELECT e.entity_id, 0, ARRAY[e.entity_id]::text[]
    FROM entities e WHERE e.entity_id = root_entity_id
    UNION ALL
    SELECT CASE WHEN r.source_entity_id = w.entity_id THEN r.target_entity_id ELSE r.source_entity_id END,
           w.depth + 1,
           w.visited || CASE WHEN r.source_entity_id = w.entity_id THEN r.target_entity_id ELSE r.source_entity_id END
    FROM walk w
    JOIN relationships r ON r.source_entity_id = w.entity_id OR r.target_entity_id = w.entity_id
    WHERE w.depth < least(greatest(coalesce(max_depth, 2), 0), 3)
      AND NOT (CASE WHEN r.source_entity_id = w.entity_id THEN r.target_entity_id ELSE r.source_entity_id END = ANY(w.visited))
  ),
  nearest AS (
    SELECT entity_id, min(depth) AS depth FROM walk GROUP BY entity_id
  ),
  selected AS (
    SELECT n.entity_id, n.depth FROM nearest n
    JOIN entities e ON e.entity_id = n.entity_id
    ORDER BY n.depth, e.canonical_name
    LIMIT least(greatest(coalesce(node_limit, 250), 1), 500)
  ),
  selected_relationships AS (
    SELECT r.* FROM relationships r
    JOIN selected a ON a.entity_id = r.source_entity_id
    JOIN selected b ON b.entity_id = r.target_entity_id
    ORDER BY r.relationship_id
    LIMIT 2000
  ),
  selected_evidence AS (
    SELECT ev.*, s.title, s.source_url, s.author, s.publisher, s.access_note
    FROM evidence ev JOIN sources s ON s.source_id = ev.source_id
    JOIN selected_relationships r ON r.relationship_id = ev.relationship_id
    ORDER BY ev.relationship_id, s.source_id
    LIMIT least(greatest(coalesce(evidence_limit, 300), 1), 1000)
  )
  SELECT jsonb_build_object(
    'root', root_entity_id,
    'depth', least(greatest(coalesce(max_depth, 2), 0), 3),
    'truncated_nodes', (SELECT count(*) FROM nearest) > (SELECT count(*) FROM selected),
    'truncated_evidence', (SELECT count(*) FROM evidence ev JOIN selected_relationships r ON r.relationship_id = ev.relationship_id)
      > least(greatest(coalesce(evidence_limit, 300), 1), 1000),
    'nodes', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'id', e.entity_id, 'name', e.canonical_name, 'type', e.entity_type,
        'cluster', e.research_cluster, 'note', e.note, 'depth', s.depth,
        'summary', es.summary_text
      ) ORDER BY s.depth, e.canonical_name)
      FROM selected s JOIN entities e ON e.entity_id = s.entity_id
      LEFT JOIN LATERAL (
        SELECT summary_text FROM entity_summaries x
        WHERE x.entity_id = e.entity_id AND x.summary_status IN ('reviewed','imported_unreviewed')
        ORDER BY x.summary_version DESC LIMIT 1
      ) es ON true
    ), '[]'::jsonb),
    'relationships', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'id', r.relationship_id, 'source', r.source_entity_id, 'target', r.target_entity_id,
        'type', r.relation_type, 'period', r.period_label, 'weight', r.weight,
        'assertion', r.assertion, 'limitation', r.limitation,
        'epistemic_status', r.epistemic_status, 'confidence', r.confidence
      ) ORDER BY r.relationship_id) FROM selected_relationships r
    ), '[]'::jsonb),
    'evidence', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'relationship_id', ev.relationship_id, 'source_id', ev.source_id,
        'title', ev.title, 'url', ev.source_url, 'author', ev.author,
        'publisher', ev.publisher, 'locator', ev.passage_locator,
        'access_note', ev.access_note, 'level', ev.evidence_level,
        'summary', ev.summary, 'independence_key', ev.independence_key
      ) ORDER BY ev.relationship_id, ev.source_id)
      FROM selected_evidence ev
    ), '[]'::jsonb)
  )
$$;

