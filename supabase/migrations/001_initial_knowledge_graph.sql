CREATE TABLE IF NOT EXISTS investigation_path_entities (
  path_id text NOT NULL REFERENCES investigation_paths(path_id) ON DELETE RESTRICT,
  entity_id text NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
  ordinal integer NOT NULL CHECK (ordinal > 0),
  membership_type text NOT NULL DEFAULT 'map_member',
